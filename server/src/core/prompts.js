// Промпты берём из shared/constants.js, а не копируем: расширение и сервер
// должны говорить с моделью одними и теми же инструкциями.
// constants.js — обычный скрипт без export, он кладёт всё в globalThis.JFC.
// Импорт нужен ради этого побочного эффекта. Обращений к chrome.* на верхнем
// уровне в нём нет (они внутри функций, которые мы не вызываем), так что в Node
// файл загружается без ошибок.
import '../../../shared/constants.js';

const JFC = globalThis.JFC;

/** Системные промпты, которые клиент обязан соблюдать. */
export const PROMPTS = Object.freeze({
  fit: JFC.FIT_CHECK_SYSTEM_PROMPT,
  ats: JFC.ATS_MATCH_SYSTEM_PROMPT,
  resumeReview: JFC.RESUME_REVIEW_SYSTEM_PROMPT
});

// Правила, которые модель должна соблюдать при написании письма. Они
// добавляются в конец промпта, потому что базовый промпт расширения задаёт тон
// и клише, но не порядок работы (сначала план, потом текст). Без плана письма
// выходят общими и без опоры на факты резюме.
export const LETTER_RULES = `ПРАВИЛА ПИСЬМА (план, затем текст):
1. Сначала план: 2-3 конкретных факта из резюме и одна связка с вакансией. Текст пишется строго по плану.
2. Не формулировать вывод за читателя: без «этот опыт научил меня», «я понял, что».
3. Называть вещи по именам: продукт работодателя, инструмент, цифра — вместо «ваши задачи», «современные технологии».
4. Не закруглять: письмо кончается конкретным следующим шагом, а не итоговой фразой о себе.
5. Только факты из резюме; чего нет в резюме, того нет в письме.
6. Писать простыми словами: «важно», «главное», «сделал» вместо торжественных оборотов вроде «стоит отметить», «играет ключевую роль».
7. Утверждать напрямую: сразу писать, что сделано, без рамки «не просто X, а Y» и «не только X, но и Y».
8. Перечислять по два пункта или по четыре, а не по три; тройное перечисление допустимо не чаще одного раза.`;

/**
 * Промпт для письма: базовые требования расширения плюс правила сервера.
 *
 * @param {string} lang 'ru' или 'en'
 * @param {string} tone 'confident' или любой другой (нейтральный тон)
 * @returns {string}
 */
export function letterPrompt(lang, tone) {
  return `${JFC.letterPrompt(lang, tone)}\n\n${LETTER_RULES}`;
}
